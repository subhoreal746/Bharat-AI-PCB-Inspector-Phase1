import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow

/**
 * Demonstration advisory generator used exclusively when inspecting bundled sample presets.
 * Never claims certified standard compliance and never alters official policy dispositions.
 */
class DemoAdvisoryEngine : AdvisoryEngine {

    override val engineLabel: String = "DemoAdvisoryEngine (Sample Presets Only)"
    override val isDemonstrationEngine: Boolean = true

    private val _modelInfo = MutableStateFlow(
        ModelInfo(
            slot = ModelSlot.AI_ADVISORY,
            displayName = "Demonstration Advisory Template",
            runtimeLabel = "Simulated Sample Advisory",
            state = ModelRuntimeState.READY,
            sha256 = "DEMO-SAMPLE-ONLY",
            contractVersion = "demo-advisory-v1",
            runtimeVersion = "demo-1.0",
            detailMessage = "Used exclusively for prototype sample boards; real inspections require an imported SmolLM2 360M ExecuTorch model.",
            isDemonstrationOnly = true
        )
    )
    override val modelInfo: StateFlow<ModelInfo> = _modelInfo.asStateFlow()

    override suspend fun initialize(): ModelOperationResult {
        return ModelOperationResult(true, "Demonstration advisory ready.")
    }

    override suspend fun generateAdvisory(request: AdvisoryRequest): AiAdvisory {
        if (!request.isDemonstration) {
            return AiAdvisory(
                availability = AdvisoryAvailability.UNAVAILABLE,
                isDemonstration = false,
                unavailableReason = "Demo advisory engine cannot run for non-demonstration inspections."
            )
        }

        val startMs = System.currentTimeMillis()
        delay(80)

        val (rootCause, action) = when {
            request.defects.isEmpty() -> {
                "No copper or solder-mask anomalies were simulated on this prototype reference board." to
                    "Proceed per line sampling protocol and verify optical lighting uniformity during live camera capture."
            }
            request.defects.any { it.severity == DefectSeverity.CRITICAL } -> {
                val names = request.defects.joinToString(", ") { it.canonicalClassName }
                "Simulated critical conductor anomaly ($names) consistent with solder bridging or etching loss." to
                    "Quarantine assembly from downstream reflow/test, inspect affected pads under 10x optical magnification, and log rework disposition."
            }
            else -> {
                val names = request.defects.joinToString(", ") { it.canonicalClassName }
                "Simulated edge/copper irregularity ($names) typical of etching over-cut or mechanical handling stress." to
                    "Perform manual optical verification of trace width clearance and confirm whether burr/notch affects current-carrying margin."
            }
        }

        val elapsed = (System.currentTimeMillis() - startMs).coerceAtLeast(1L)
        return AiAdvisory(
            availability = AdvisoryAvailability.AVAILABLE,
            isDemonstration = true,
            severityClassification = request.officialDisposition.name,
            probableRootCause = rootCause,
            recommendedOperatorAction = action,
            relevantStandard = "None verified (prototype demonstration sample; no authoritative standard document attached).",
            suggestedDisposition = request.officialDisposition,
            limitations = "Demonstration advisory derived from prototype sample metadata only; not generated by SmolLM2 360M ExecuTorch.",
            advisoryLatencyMs = elapsed,
            provenanceSummary = "DemoAdvisoryEngine • contract=demo-advisory-v1"
        )
    }

    override suspend fun unload() = Unit
    override suspend fun close() = Unit
}
